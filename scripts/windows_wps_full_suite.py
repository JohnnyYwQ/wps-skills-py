def iter_declared_actions() -> Iterator[Tuple[str, str]]:
    """Yield every explicitly declared ``(owner, action)`` identity."""

    for scenario in SCENARIOS:
        for action in scenario.actions:
            yield scenario.owner, action


def scenarios_for(owner: str) -> Tuple[Scenario, ...]:
    """Return scenarios for one Action owner."""

    return tuple(scenario for scenario in SCENARIOS if scenario.owner == owner)


