def build_action_params(owner: str, action: str, state: dict) -> dict:
    """Build a valid, deterministic parameter object for one live Action case."""

    if owner == "bridge":
        return {}
    if owner == "excel":
        return _excel_params(action, state)
    if owner == "ppt":
        return _ppt_params(action, state)
    if owner == "word":
        return _word_params(action, state)
    raise ValueError(f"unsupported suite owner: {owner}")
